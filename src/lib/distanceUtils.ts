/**
 * Normalizes an Israeli city name for matching
 */
export function normalizeCityName(city: string): string {
    if (!city) return '';
    let normalized = city.trim().replace(/-/g, ' ').replace(/[\u200B-\u200D\uFEFF]/g, '');
    normalized = normalized.replace(/^ב?מרכז /g, ''); // strip "במרכז"
    normalized = normalized.replace(/,.*$/, ''); // strip everything after comma
    return normalized.trim();
}

/**
 * Extracts the primary city from a location string (e.g., "יגאל אלון 98 תל אביב" -> "תל אביב")
 * Falls back to finding if any known city is in the string.
 */
export function extractCityFromLocation(locationString: string): string | null {
    if (!locationString) return null;
    const normalized = locationString.toLowerCase().replace(/-/g, ' ');
    
    // First try exact matches
    const exactMatch = Object.keys(ISRAEL_CITIES).find(city => normalized.includes(city));
    if (exactMatch) return exactMatch;
    
    return null;
}

/**
 * Calculates the distance between two points in km using the Haversine formula
 */
function haversineDistance(lat1: number, lon1: number, lat2: number, lon2: number): number {
    const R = 6371; // Earth's radius in km
    const dLat = (lat2 - lat1) * Math.PI / 180;
    const dLon = (lon2 - lon1) * Math.PI / 180;
    const a = 
        Math.sin(dLat/2) * Math.sin(dLat/2) +
        Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * 
        Math.sin(dLon/2) * Math.sin(dLon/2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
    return R * c;
}

/**
 * Checks if a job location is within the specified distance from a preferred location
 */
export function isLocationWithinDistance(jobLocation: string, preferredLocation: string, maxDistanceKm: number): boolean {
    if (!jobLocation || !preferredLocation) return true; // If missing info, don't filter out
    if (jobLocation.includes('עבודה מהבית') || jobLocation.toLowerCase().includes('remote') || jobLocation === 'Remote') return true;
    
    // Check for exact substring match first (e.g. they both say "תל אביב")
    if (jobLocation.includes(preferredLocation) || preferredLocation.includes(jobLocation)) {
        return true;
    }
    
    const city1 = extractCityFromLocation(preferredLocation);
    const city2 = extractCityFromLocation(jobLocation);
    
    if (city1 && city2 && ISRAEL_CITIES[city1] && ISRAEL_CITIES[city2]) {
        const coords1 = ISRAEL_CITIES[city1];
        const coords2 = ISRAEL_CITIES[city2];
        const distance = haversineDistance(coords1.lat, coords1.lon, coords2.lat, coords2.lon);
        return distance <= maxDistanceKm;
    }
    
    // If we can't parse one of the cities, we fallback to true to avoid over-filtering
    // or we could fallback to string inclusion
    return true;
}
